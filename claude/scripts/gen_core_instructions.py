#!/usr/bin/env python3
"""gen_core_instructions.py — compose agent-toolkit's CORE_INSTRUCTIONS.md +
personal-overlay.md into claude/global-instructions.md.

Dotfiles-only tool: agent-toolkit has no personal-overlay.md to compose
against and symlinks its claude/CORE_INSTRUCTIONS.md directly instead. The
shareable core is read live from the agent-toolkit checkout -- this repo
keeps no copy of it, so there is no second copy to drift -- and joined with
this machine's personal-policy overlay in a fixed append-at-end order, with
no markup in either input file. install-with-agent-toolkit.sh runs this after
every real install, and watchcommit's pre-tick hook (scripts/watchcommit-pre-tick)
runs it after every clean background pull, so the committed output tracks
agent-toolkit's current core within a couple of watchcommit polls.

Provenance and the forward-only rule: the core is read from the last
agent-toolkit commit that touched claude/CORE_INSTRUCTIONS.md (its committed
blob, not the working tree -- uncommitted core edits are never composed), and
that commit is recorded on the line after the do-not-edit marker as
``<!-- agent-toolkit source: <sha> -->``. The output is shared across machines
through git while each machine composes from its own checkout, so a write
only moves the file forward: it is skipped (exit 3) unless the recorded
commit is the local source commit or an ancestor of it. A machine whose
agent-toolkit is behind, or diverged, therefore never rolls the file back and
never fights another machine over it; --force overrides. The check and the
write happen under an exclusive lock on claude/.global-instructions.md.lock.

Merge driver: if two machines still commit different compositions in the
same watchcommit poll, the second one's rebase would conflict. Every
write-mode run therefore first registers this script as the repo-local git
merge driver for the file (.gitattributes names it; git only takes the
command from config): ``merge.global-instructions.driver`` runs
``--merge-driver %O %A %B`` with this interpreter and this checkout, and the
write is refused if registration fails. The driver never text-merges: it
keeps whichever side's recorded source is forward of the other, after
checking each side's core against the commit it names, and copies that side
byte-for-byte. Byte-identical sides merge cleanly. Anything else -- an
overlay mismatch, diverged or missing commits, a hand-edited core,
unparseable content, any git failure -- exits 1, which git turns into an
unmerged path holding the upstream side (no conflict markers); watchcommit
then aborts the rebase as before. To resolve one by hand, inspect both sides
(``git show :2:claude/global-instructions.md`` and ``:3:``) and keep the one
you intend, or abort, pull agent-toolkit and retry -- never blindly
recompose and ``git add``.

The checkout is resolved by dotfiles_cli_common.agent_toolkit_checkout:
--agent-toolkit-path, else $AGENT_TOOLKIT_PATH, else
~/Workspace/agent-toolkit/agent-toolkit, else ~/Workspace/agent-toolkit.

Usage:
    python3 claude/scripts/gen_core_instructions.py            write global-instructions.md
    python3 claude/scripts/gen_core_instructions.py --check     exit 1 if stale
    python3 claude/scripts/gen_core_instructions.py --stdout    print, write nothing
    python3 claude/scripts/gen_core_instructions.py --print-agent-toolkit-path
    python3 claude/scripts/gen_core_instructions.py --merge-driver BASE OURS THEIRS

Flags: --check, --stdout, --print-agent-toolkit-path, --merge-driver <3 paths>,
--force,
--agent-toolkit-path <path>, --core-path <file>, --repo-root <path>,
--quiet/-q, --verbose/-v.
Env vars: AGENT_TOOLKIT_PATH (agent-toolkit checkout; set but not a checkout is
an error, never a fallback).
Files read: claude/CORE_INSTRUCTIONS.md at the agent-toolkit source commit
(via git; or --core-path, recorded as source "unknown"),
<repo>/claude/personal-overlay.md.
Files written: <repo>/claude/global-instructions.md, atomically and only when
its content changes (skipped by --check, --stdout and
--print-agent-toolkit-path); <repo>/claude/.global-instructions.md.lock;
<repo>'s local git config (merge.global-instructions.*, on every write-mode
run); OURS, in --merge-driver mode.
Exit codes: 0 written or already up to date; 1 --check found stale output;
2 bad usage, an unresolvable checkout, a missing or unreadable input, or a
git failure (always reported, even with -q); 3 write skipped by the
forward-only rule (reported on stderr unless -q). --merge-driver: 0 resolved,
1 left unresolved (OURS untouched).

Requires Python 3.12+.
"""

import argparse
import fcntl
import os
import re
import subprocess
import sys
import tempfile
from collections.abc import Iterator, Sequence
from contextlib import contextmanager
from pathlib import Path

import dotfiles_cli_common as cli_common

DO_NOT_EDIT_MARKER = (
    "<!-- generated by claude/scripts/gen_core_instructions.py — do not edit; "
    "edit agent-toolkit's claude/CORE_INSTRUCTIONS.md (shareable) or "
    "dotfiles' claude/personal-overlay.md (this machine's personal policy) "
    "instead, then regenerate -->"
)


CORE_RELPATH = "claude/CORE_INSTRUCTIONS.md"
UNKNOWN_SOURCE = "unknown"
PROVENANCE_RE = re.compile(r"^<!-- agent-toolkit source: (\S+) -->$", re.MULTILINE)


MERGE_DRIVER_NAME = "global-instructions"
MERGE_DRIVER_LABEL = "global-instructions.md: keep the forward-most agent-toolkit core"


class ComposeError(Exception):
    """Composition cannot proceed; always reported, exit 2."""


class ForwardOnlySkip(Exception):
    """The write would move the output backwards or sideways; exit 3."""


def compose_text(core_text: str, overlay_text: str, source: str) -> str:
    """Join core, marker, provenance line and overlay in the fixed order.

    No substitution markup in either input and no rewriting of the core:
    CORE_INSTRUCTIONS.md must remain valid, self-contained instructions on
    its own, since agent-toolkit symlinks it directly with no generation step.
    """
    core = core_text.rstrip("\n")
    overlay = overlay_text.rstrip("\n")
    provenance = f"<!-- agent-toolkit source: {source} -->"
    return f"{core}\n\n{DO_NOT_EDIT_MARKER}\n{provenance}\n\n{overlay}\n"


def recorded_source(text: str) -> str | None:
    """Return the source commit recorded in composed ``text``, if any."""
    match = PROVENANCE_RE.search(text)
    return match.group(1) if match else None


def _git(checkout: Path, *args: str) -> subprocess.CompletedProcess[str]:
    try:
        return subprocess.run(
            ["git", "-C", str(checkout), *args],
            capture_output=True,
            text=True,
            check=False,
        )
    except OSError as exc:
        raise ComposeError(f"cannot run git in {checkout}: {exc}") from exc


def _git_out(checkout: Path, *args: str) -> str:
    result = _git(checkout, *args)
    if result.returncode != 0:
        raise ComposeError(
            f"git {' '.join(args)} failed in {checkout}: {result.stderr.strip()}"
        )
    return result.stdout


def read_core_at_source(checkout: Path) -> tuple[str, str]:
    """Return (source commit, core text at that commit) from ``checkout``.

    The source commit is the last one touching the core, so unrelated
    agent-toolkit commits never change the output; reading its blob rather
    than the working tree keeps the recorded commit and the bytes in step.
    """
    sha = _git_out(checkout, "log", "-1", "--format=%H", "--", CORE_RELPATH).strip()
    if not sha:
        raise ComposeError(f"no commit touches {CORE_RELPATH} in {checkout}")
    return sha, _git_out(checkout, "show", f"{sha}:{CORE_RELPATH}")


def check_forward(checkout: Path, recorded: str | None, local: str) -> None:
    """Raise ForwardOnlySkip unless replacing ``recorded`` with ``local`` is forward.

    A missing object (not fetched yet) and a non-ancestor are expected skips;
    any other git failure is a ComposeError, never silenced.
    """
    if recorded in (None, UNKNOWN_SOURCE, local):
        return
    if _git(checkout, "cat-file", "-e", f"{recorded}^{{commit}}").returncode != 0:
        if _git(checkout, "cat-file", "-e", recorded).returncode == 0:
            raise ComposeError(
                f"recorded agent-toolkit source {recorded} exists in {checkout} "
                "but is not a commit"
            )
        raise ForwardOnlySkip(
            f"composed from agent-toolkit {recorded}, which {checkout} does not "
            "have yet -- pull agent-toolkit, or pass --force"
        )
    result = _git(checkout, "merge-base", "--is-ancestor", recorded, local)
    if result.returncode == 1:
        raise ForwardOnlySkip(
            f"composed from agent-toolkit {recorded}, which is not an ancestor of "
            f"this checkout's core commit {local} -- pull agent-toolkit, or pass "
            "--force"
        )
    if result.returncode != 0:
        raise ComposeError(
            f"git merge-base --is-ancestor {recorded} {local} failed in "
            f"{checkout}: {result.stderr.strip()}"
        )


def register_merge_driver(repo_root: Path, python: str, checkout: Path | None) -> None:
    """Point the repo's ``merge.global-instructions`` driver at this script.

    A no-op outside a git work tree (no race is possible there). Raises
    ComposeError if a path cannot be quoted safely or the config write does
    not stick, so callers refuse to compose rather than create a commit the
    repo could not resolve.
    """
    inside = _git(repo_root, "rev-parse", "--is-inside-work-tree")
    if inside.returncode != 0 or inside.stdout.strip() != "true":
        return
    parts = [python] + ([] if checkout is None else [str(checkout)])
    for part in parts:
        if "'" in part:
            raise ComposeError(
                f"cannot register the merge driver: {part!r} contains a quote"
            )
    command = f"'{python}' claude/scripts/gen_core_instructions.py"
    if checkout is not None:
        command += f" --agent-toolkit-path '{checkout}'"
    command += " --merge-driver %O %A %B"
    for key, value in (("name", MERGE_DRIVER_LABEL), ("driver", command)):
        result = _git(
            repo_root, "config", "--local", f"merge.{MERGE_DRIVER_NAME}.{key}", value
        )
        if result.returncode != 0:
            raise ComposeError(
                f"cannot register the merge driver in {repo_root}: "
                f"{result.stderr.strip()}"
            )
    stored = _git(
        repo_root, "config", "--local", "--get", f"merge.{MERGE_DRIVER_NAME}.driver"
    )
    if stored.stdout.strip() != command:
        raise ComposeError(
            f"cannot register the merge driver in {repo_root}: config did not stick"
        )


def _normalize(text: str) -> str:
    return text.replace("\r\n", "\n")


def parse_composed(text: str) -> tuple[str, str, str] | None:
    """Split normalized composed text into (core, source, overlay), or None."""
    text = _normalize(text)
    core, marker, rest = text.partition(DO_NOT_EDIT_MARKER)
    if not marker or not rest.startswith("\n"):
        return None
    line, newline, overlay = rest[1:].partition("\n")
    match = PROVENANCE_RE.fullmatch(line)
    if match is None or not newline:
        return None
    return core.rstrip("\n"), match.group(1), overlay.strip("\n")


class _Unresolved(Exception):
    """The driver cannot pick a side safely; leave the conflict."""


def _check_side_core(checkout: Path, core: str, source: str) -> None:
    if source == UNKNOWN_SOURCE:
        raise _Unresolved("a side was composed without a known agent-toolkit source")
    if _git(checkout, "cat-file", "-e", f"{source}^{{commit}}").returncode != 0:
        raise _Unresolved(f"agent-toolkit {source} is not a commit in {checkout}")
    shown = _git(checkout, "show", f"{source}:{CORE_RELPATH}")
    if shown.returncode != 0:
        raise _Unresolved(f"cannot read {CORE_RELPATH} at {source}")
    if _normalize(shown.stdout).rstrip("\n") != core:
        raise _Unresolved(f"a side's core does not match agent-toolkit {source}")


def _is_ancestor(checkout: Path, older: str, newer: str) -> bool:
    result = _git(checkout, "merge-base", "--is-ancestor", older, newer)
    if result.returncode not in (0, 1):
        raise _Unresolved(f"git merge-base failed: {result.stderr.strip()}")
    return result.returncode == 0


def _select_side(
    explicit_checkout: Path | None, ours_bytes: bytes, theirs_bytes: bytes
) -> tuple[bool, str]:
    """Return (take_theirs, reason) or raise _Unresolved; never writes."""
    sides = []
    for raw in (ours_bytes, theirs_bytes):
        parsed = parse_composed(raw.decode("utf-8"))
        if parsed is None:
            raise _Unresolved("a side is not a composed global-instructions.md")
        sides.append(parsed)
    (ours_core, ours_src, ours_overlay), (theirs_core, theirs_src, theirs_overlay) = (
        sides
    )
    if ours_overlay != theirs_overlay:
        raise _Unresolved("the personal overlays differ -- resolve by hand")
    if ours_src == theirs_src:
        raise _Unresolved(f"both sides claim {ours_src} but differ")
    try:
        checkout = cli_common.agent_toolkit_checkout(explicit=explicit_checkout)
    except cli_common.AgentToolkitNotFoundError as exc:
        raise _Unresolved(str(exc)) from exc
    _check_side_core(checkout, ours_core, ours_src)
    _check_side_core(checkout, theirs_core, theirs_src)
    if _is_ancestor(checkout, theirs_src, ours_src):
        return False, f"kept {ours_src[:12]} (forward of {theirs_src[:12]})"
    if _is_ancestor(checkout, ours_src, theirs_src):
        return True, f"took {theirs_src[:12]} (forward of {ours_src[:12]})"
    raise _Unresolved(f"{ours_src} and {theirs_src} have diverged")


def merge_driver(explicit_checkout: Path | None, ours: Path, theirs: Path) -> int:
    """Resolve a global-instructions.md conflict by whole-side selection.

    ``ours`` is git's %A (upstream plus what is replayed so far), ``theirs``
    %B. Returns 0 with the chosen side in ``ours``, or 1 leaving ``ours``
    untouched.
    """
    try:
        ours_bytes, theirs_bytes = ours.read_bytes(), theirs.read_bytes()
        if ours_bytes == theirs_bytes:
            return 0
        take_theirs, reason = _select_side(explicit_checkout, ours_bytes, theirs_bytes)
        if take_theirs:
            write_atomically_bytes(ours, theirs_bytes)
    except (_Unresolved, ComposeError, OSError, UnicodeDecodeError) as exc:
        print(f"[gen_core_instructions] merge: left unresolved: {exc}", file=sys.stderr)
        return 1
    print(f"[gen_core_instructions] merge: {reason}", file=sys.stderr)
    return 0


@contextmanager
def output_lock(output_path: Path) -> Iterator[None]:
    """Hold an exclusive lock serializing every composer writing ``output_path``."""
    lock_path = output_path.with_name(f".{output_path.name}.lock")
    with open(lock_path, "a", encoding="utf-8") as handle:
        fcntl.flock(handle, fcntl.LOCK_EX)
        try:
            yield
        finally:
            fcntl.flock(handle, fcntl.LOCK_UN)


def write_atomically(path: Path, text: str) -> None:
    """Write ``text`` to ``path`` so a reader never sees a partial file."""
    write_atomically_bytes(path, text.encode("utf-8"))


def write_atomically_bytes(path: Path, data: bytes) -> None:
    """Write ``data`` to ``path`` so a reader never sees a partial file."""
    fd, temp_name = tempfile.mkstemp(dir=path.parent, prefix=f".{path.name}.")
    temp_path = Path(temp_name)
    try:
        with os.fdopen(fd, "wb") as handle:
            handle.write(data)
        os.replace(temp_path, path)
    except BaseException:
        temp_path.unlink(missing_ok=True)
        raise


def default_repo_root() -> Path:
    """Return the repo root inferred from this script's real location."""
    return Path(__file__).resolve().parents[2]


def build_parser() -> argparse.ArgumentParser:
    """Build the CLI parser."""
    parser = argparse.ArgumentParser(
        prog="gen_core_instructions",
        description="compose agent-toolkit's CORE_INSTRUCTIONS.md + "
        "personal-overlay.md into global-instructions.md",
    )
    cli_common.add_verbosity_args(parser)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument(
        "--check",
        action="store_true",
        help="exit 1 (with a diff-free notice on stderr) if the output is stale",
    )
    mode.add_argument(
        "--stdout", action="store_true", help="print the composed file, write nothing"
    )
    mode.add_argument(
        "--print-agent-toolkit-path",
        action="store_true",
        help="print the resolved agent-toolkit checkout and exit",
    )
    mode.add_argument(
        "--merge-driver",
        nargs=3,
        type=Path,
        default=None,
        metavar=("BASE", "OURS", "THEIRS"),
        help="act as git's merge driver for global-instructions.md (%%O %%A %%B)",
    )
    parser.add_argument(
        "--force",
        action="store_true",
        help="write even when the forward-only rule would skip",
    )
    parser.add_argument(
        "--agent-toolkit-path",
        type=Path,
        default=None,
        metavar="<path>",
        help="agent-toolkit checkout (default: $AGENT_TOOLKIT_PATH, then the "
        "nested, then the flat ~/Workspace layout)",
    )
    parser.add_argument(
        "--core-path",
        type=Path,
        default=None,
        metavar="<file>",
        help="read the core from this file instead of resolving a checkout",
    )
    parser.add_argument(
        "--repo-root",
        type=Path,
        default=None,
        metavar="<path>",
        help="repository root (default: inferred from this script's path)",
    )
    return parser


def main(argv: Sequence[str] | None = None) -> int:
    """Parse argv, then compose, check, print, or resolve; return the exit code."""
    args = build_parser().parse_args(argv)

    def fail(message: str) -> int:
        print(f"[gen_core_instructions] {message}", file=sys.stderr)
        return 2

    if args.merge_driver is not None:
        # BASE is ignored: provenance ancestry decides, not a 3-way text merge.
        _base, ours, theirs = args.merge_driver
        return merge_driver(args.agent_toolkit_path, ours, theirs)

    repo_root = (args.repo_root or default_repo_root()).resolve()
    output_path = repo_root / "claude" / "global-instructions.md"
    overlay_path = repo_root / "claude" / "personal-overlay.md"

    checkout: Path | None = None
    if args.core_path is None or args.print_agent_toolkit_path:
        try:
            checkout = cli_common.agent_toolkit_checkout(
                explicit=args.agent_toolkit_path
            )
        except cli_common.AgentToolkitNotFoundError as exc:
            return fail(str(exc))
        if args.print_agent_toolkit_path:
            print(checkout)
            return 0

    try:
        if args.core_path is not None:
            source = UNKNOWN_SOURCE
            core_text = args.core_path.read_text(encoding="utf-8")
        else:
            assert checkout is not None
            source, core_text = read_core_at_source(checkout)
        overlay_text = overlay_path.read_text(encoding="utf-8")
    except ComposeError as exc:
        return fail(str(exc))
    except (OSError, UnicodeDecodeError) as exc:
        # Exit 2, not an uncaught crash: a crash exits 1, which --check
        # callers (the wrapper's dry run) read as merely "stale".
        return fail(str(exc))
    composed = compose_text(core_text, overlay_text, source)

    if args.stdout:
        sys.stdout.write(composed)
        return 0

    if args.check:
        try:
            current = (
                output_path.read_text(encoding="utf-8") if output_path.is_file() else ""
            )
        except (OSError, UnicodeDecodeError) as exc:
            return fail(str(exc))
        if current == composed:
            cli_common.qprint(
                "[gen_core_instructions] global-instructions.md is up to date",
                quiet=args.quiet,
            )
            return 0
        print(
            "[gen_core_instructions] stale — run "
            "`python3 claude/scripts/gen_core_instructions.py`",
            file=sys.stderr,
        )
        return 1

    try:
        register_merge_driver(repo_root, sys.executable, checkout)
        with output_lock(output_path):
            current = (
                output_path.read_text(encoding="utf-8")
                if output_path.is_file()
                else None
            )
            if current == composed:
                cli_common.qprint(
                    "[gen_core_instructions] global-instructions.md is up to date",
                    quiet=args.quiet,
                )
                return 0
            if checkout is not None and not args.force:
                recorded = recorded_source(current) if current is not None else None
                check_forward(checkout, recorded, source)
            write_atomically(output_path, composed)
    except ForwardOnlySkip as exc:
        cli_common.qprint(
            f"[gen_core_instructions] skipped: {exc}",
            quiet=args.quiet,
            file=sys.stderr,
        )
        return 3
    except ComposeError as exc:
        return fail(str(exc))
    except (OSError, UnicodeDecodeError) as exc:
        return fail(str(exc))
    cli_common.qprint(
        "[gen_core_instructions] wrote claude/global-instructions.md", quiet=args.quiet
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
